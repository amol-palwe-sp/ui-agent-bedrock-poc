package com.sailpoint.poc.uiagent.eval.shared;

import com.sailpoint.poc.uiagent.TokenUsage;
import com.sailpoint.poc.uiagent.bedrock.BedrockAnthropicClient;
import com.sailpoint.poc.uiagent.eval.benchmark.EvalCase;
import com.sailpoint.poc.uiagent.video.VideoAnalysisResult;
import org.json.JSONArray;
import org.json.JSONObject;

import java.util.ArrayList;
import java.util.List;

/**
 * LLM-as-Judge for both benchmark and real-time eval modes.
 *
 * <p>Uses the existing {@link BedrockAnthropicClient} to call Claude.
 * Works with ground truth ({@link #judge}) and without ({@link #judgeWithoutGroundTruth}).
 */
public final class LlmJudge {

    private static final String SYSTEM_PROMPT =
            "You are an expert evaluator of UI navigation automation scripts. "
            + "Your job is to assess the quality of navigation steps generated by an AI agent "
            + "from video recordings. Be precise, fair, and consistent. "
            + "Always respond with valid JSON only — no markdown fences, no explanation outside JSON.";

    private LlmJudge() {}

    // ── JudgeResult record ────────────────────────────────────────────────────

    /**
     * Structured result from one LLM judge invocation.
     */
    public record JudgeResult(
            double       correctness,
            double       order,
            double       hallucination,
            double       labelQuality,
            double       placeholder,
            double       overall,
            String       reasoning,
            List<String> hallucinatedSteps,
            List<String> missingSteps,
            int          confidenceScore,
            List<String> warnings,
            String       recommendation,
            TokenUsage   tokenUsage) {

        /** Returns a zero-score fallback result used when the LLM call fails. */
        public static JudgeResult failure(String reason) {
            return new JudgeResult(0, 0, 0, 0, 0, 0,
                    "Judge call failed: " + reason,
                    List.of(), List.of(), 0, List.of("Judge unavailable"), "CAUTION",
                    TokenUsage.ZERO);
        }
    }

    // ── Benchmark mode (with ground truth) ───────────────────────────────────

    /**
     * Judges generated steps against ground truth steps (benchmark mode).
     *
     * @param evalCase  the benchmark case with ground truth
     * @param generated the parsed result from Claude
     * @param bedrock   the Bedrock client to use
     * @return a populated JudgeResult
     */
    public static JudgeResult judge(
            EvalCase evalCase,
            VideoAnalysisResult generated,
            BedrockAnthropicClient bedrock) {

        String userPrompt = buildBenchmarkPrompt(evalCase, generated);
        try {
            BedrockAnthropicClient.InvokeResult result =
                    bedrock.invokeWithVision(SYSTEM_PROMPT, userPrompt, null);
            return parseJudgeResponse(result.text(), result.usage());
        } catch (Exception e) {
            return JudgeResult.failure(e.getMessage());
        }
    }

    // ── Real-time mode (without ground truth) ────────────────────────────────

    /**
     * Judges generated steps for self-consistency without ground truth (real-time mode).
     *
     * @param generated the parsed result from Claude
     * @param taskType  "AGGREGATION" or "PROVISIONING"
     * @param mode      "PLACEHOLDER" or "LITERAL"
     * @param bedrock   the Bedrock client to use
     * @return a populated JudgeResult
     */
    public static JudgeResult judgeWithoutGroundTruth(
            VideoAnalysisResult generated,
            String taskType,
            String mode,
            BedrockAnthropicClient bedrock) {

        String userPrompt = buildRealtimePrompt(generated, taskType, mode);
        try {
            BedrockAnthropicClient.InvokeResult result =
                    bedrock.invokeWithVision(SYSTEM_PROMPT, userPrompt, null);
            return parseJudgeResponse(result.text(), result.usage());
        } catch (Exception e) {
            return JudgeResult.failure(e.getMessage());
        }
    }

    // ── Prompt builders ───────────────────────────────────────────────────────

    private static String buildBenchmarkPrompt(EvalCase evalCase, VideoAnalysisResult generated) {
        EvalCase.GroundTruth gt = evalCase.groundTruth();
        boolean isAggregation  = evalCase.isAggregation();
        boolean isPlaceholder  = "PLACEHOLDER".equalsIgnoreCase(evalCase.mode());

        StringBuilder sb = new StringBuilder();
        sb.append("You are evaluating a navigation goal script generated by an AI agent from a video recording.\n\n");
        sb.append("TASK TYPE: ").append(evalCase.taskType()).append("\n");
        sb.append("MODE: ").append(evalCase.mode()).append("\n\n");

        // Show ground truth as a single assembled goal string — this is what the agent executes
        sb.append("GROUND TRUTH NAVIGATION GOAL:\n");
        sb.append(gt.navigationGoal().isBlank() ? "(not provided)" : gt.navigationGoal()).append("\n");

        sb.append("\nGENERATED NAVIGATION GOAL:\n");
        sb.append(generated.navigationGoal().isBlank() ? "(empty)" : generated.navigationGoal()).append("\n");

        if (isAggregation && generated.paginationPattern() != null) {
            sb.append("\nGENERATED PAGINATION PATTERN:\n");
            sb.append("  type: ").append(generated.paginationPattern().type()).append("\n");
            sb.append("  description: ").append(generated.paginationPattern().description()).append("\n");
            sb.append("  selectorHint: ").append(generated.paginationPattern().selectorHint()).append("\n");

            if (gt.paginationPattern() != null) {
                sb.append("\nEXPECTED PAGINATION PATTERN:\n");
                sb.append("  type: ").append(gt.paginationPattern().type()).append("\n");
                sb.append("  description: ").append(gt.paginationPattern().description()).append("\n");
                sb.append("  selectorHint: ").append(gt.paginationPattern().selectorHint()).append("\n");
            }
        }

        sb.append("\nEVALUATION CRITERIA (compare the two goal strings above):\n");
        sb.append("1. correctness (0-10): Does the generated goal cover the same actions as ground truth?\n");
        sb.append("2. order (0-10): Are the actions in the same chronological order as ground truth?\n");
        sb.append("3. hallucination (0-10): 10 = no invented actions; 0 = many actions not in ground truth.\n");
        sb.append("4. label_quality (0-10): Do UI element labels (field names, button labels) match ground truth?\n");
        if (isPlaceholder) {
            sb.append("5. placeholder (0-10): This is PLACEHOLDER mode. EVERY value the user enters or selects into a field "
                    + "must appear as a {Token} placeholder (e.g. \"{Email}\", \"{Password}\"), never a literal value. "
                    + "10 = all entered/selected values are placeholders; 0 = one or more literal credentials/values remain.\n");
        } else {
            sb.append("5. placeholder (0-10): LITERAL mode — no placeholder required. Give 10.\n");
        }
        sb.append("6. overall (0-10): Holistic quality — would this script navigate the same UI workflow as ground truth?\n");

        sb.append("\nFor hallucinated_steps list the action phrases present in GENERATED but absent from GROUND TRUTH.\n");
        sb.append("For missing_steps list the action phrases present in GROUND TRUTH but absent from GENERATED.\n");

        sb.append("\nRespond ONLY with this JSON (no markdown, no extra text):\n");
        sb.append("{\n");
        sb.append("  \"correctness\": <0-10>,\n");
        sb.append("  \"order\": <0-10>,\n");
        sb.append("  \"hallucination\": <0-10>,\n");
        sb.append("  \"label_quality\": <0-10>,\n");
        sb.append("  \"placeholder\": <0-10>,\n");
        sb.append("  \"overall\": <0-10>,\n");
        sb.append("  \"reasoning\": \"brief explanation\",\n");
        sb.append("  \"hallucinated_steps\": [\"action phrase not in GT\"],\n");
        sb.append("  \"missing_steps\": [\"GT action phrase not in generated\"],\n");
        sb.append("  \"confidence_score\": <0-100>,\n");
        sb.append("  \"warnings\": [\"warning message\"],\n");
        sb.append("  \"recommendation\": \"TRUST|REVIEW|CAUTION\"\n");
        sb.append("}\n");

        return sb.toString();
    }

    private static String buildRealtimePrompt(
            VideoAnalysisResult generated, String taskType, String mode) {
        boolean isAggregation = "AGGREGATION".equalsIgnoreCase(taskType);
        boolean isPlaceholder = "PLACEHOLDER".equalsIgnoreCase(mode);
        int stepCount = generated.steps().size();

        StringBuilder sb = new StringBuilder();
        sb.append("You are evaluating a navigation goal script generated by an AI agent from a video recording.\n");
        sb.append("There is NO ground truth. Give a holistic confidence score — do NOT enumerate every possible concern.\n\n");
        sb.append("TASK TYPE: ").append(taskType).append("\n");
        sb.append("TARGET URL: ").append(generated.targetUrl().isBlank() ? "(not specified)" : generated.targetUrl()).append("\n");
        sb.append("STEP COUNT: ").append(stepCount).append("\n\n");

        sb.append("GENERATED NAVIGATION GOAL:\n");
        sb.append(generated.navigationGoal().isBlank() ? "(empty)" : generated.navigationGoal()).append("\n");

        if (isAggregation && generated.paginationPattern() != null) {
            sb.append("\nPAGINATION PATTERN: type=").append(generated.paginationPattern().type())
              .append(", description=").append(generated.paginationPattern().description()).append("\n");
        }

        sb.append("\nSCORING GUIDE:\n");
        sb.append("- confidence_score 0-100: overall trustworthiness of this script\n");
        sb.append("- overall 0-10: holistic quality\n");
        sb.append("- correctness 0-10: plausible, complete UI workflow\n");
        sb.append("- order 0-10: logical chronological sequence\n");
        sb.append("- hallucination 0-10: 10=grounded actions, 0=invented/contradictory\n");
        sb.append("- label_quality 0-10: specific, unambiguous UI element names\n");
        if (isPlaceholder) {
            sb.append("- placeholder 0-10: every entered/selected value uses a {Token} placeholder (not a literal value)\n");
        } else {
            sb.append("- placeholder: give 10 (LITERAL mode — no check needed)\n");
        }
        sb.append("\nOnly add warnings for clear structural problems: empty goal, impossible action order, ");
        sb.append("or completely missing required actions (e.g. no login steps before navigation).\n");
        sb.append("Do NOT warn about specific label choices, individual credential values, or assumed missing navigation steps.\n");

        sb.append("\nRespond ONLY with this JSON (no markdown, no extra text):\n");
        sb.append("{\n");
        sb.append("  \"correctness\": <0-10>,\n");
        sb.append("  \"order\": <0-10>,\n");
        sb.append("  \"hallucination\": <0-10>,\n");
        sb.append("  \"label_quality\": <0-10>,\n");
        sb.append("  \"placeholder\": <0-10>,\n");
        sb.append("  \"overall\": <0-10>,\n");
        sb.append("  \"reasoning\": \"1-2 sentence holistic assessment\",\n");
        sb.append("  \"hallucinated_steps\": [],\n");
        sb.append("  \"missing_steps\": [],\n");
        sb.append("  \"confidence_score\": <0-100>,\n");
        sb.append("  \"warnings\": [],\n");
        sb.append("  \"recommendation\": \"TRUST|REVIEW|CAUTION\"\n");
        sb.append("}\n");

        return sb.toString();
    }

    // ── Response parser ───────────────────────────────────────────────────────

    private static JudgeResult parseJudgeResponse(String rawText, TokenUsage usage) {
        try {
            JSONObject j = BedrockAnthropicClient.parseModelJson(rawText);

            double correctness  = j.optDouble("correctness",      0.0);
            double order        = j.optDouble("order",             0.0);
            double hallucination = j.optDouble("hallucination",    0.0);
            double labelQuality = j.optDouble("label_quality",     0.0);
            double placeholder  = j.optDouble("placeholder",       0.0);
            double overall      = j.optDouble("overall",           0.0);
            String reasoning    = j.optString("reasoning",         "");
            int confidenceScore = j.optInt("confidence_score",     0);
            String recommendation = j.optString("recommendation", "CAUTION");

            List<String> hallucinatedSteps = parseStringArray(j.optJSONArray("hallucinated_steps"));
            List<String> missingSteps      = parseStringArray(j.optJSONArray("missing_steps"));
            List<String> warnings          = parseStringArray(j.optJSONArray("warnings"));

            // Normalize recommendation
            if (!recommendation.equals("TRUST") && !recommendation.equals("REVIEW")) {
                recommendation = "CAUTION";
            }
            if (confidenceScore >= 85 && warnings.isEmpty()) recommendation = "TRUST";
            else if (confidenceScore >= 60) recommendation = "REVIEW";
            else recommendation = "CAUTION";

            return new JudgeResult(
                    correctness, order, hallucination, labelQuality, placeholder, overall,
                    reasoning, hallucinatedSteps, missingSteps,
                    confidenceScore, warnings, recommendation, usage);

        } catch (Exception e) {
            return JudgeResult.failure("JSON parse error: " + e.getMessage());
        }
    }

    private static List<String> parseStringArray(JSONArray arr) {
        List<String> list = new ArrayList<>();
        if (arr == null) return list;
        for (int i = 0; i < arr.length(); i++) {
            String s = arr.optString(i, "").trim();
            if (!s.isBlank()) list.add(s);
        }
        return list;
    }
}
